# algoritmos e introducción a bucles
# funciones max() y min()

print()
input1 = int(input('Ingresa el primer numero: '))
input2 = int(input('Ingresa el segundo numero: '))
input3 = int(input('Ingresa el tercer numero: '))

# Verificar el número mayor
numMayor = max(input1, input2, input3)

print(numMayor)

# Verificar el número menor
numMenor = min(input1, input2, input3)

print(numMenor)
print()

